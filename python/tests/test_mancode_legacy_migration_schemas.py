def test_mancode_legacy_projection_schema_is_valid_and_non_authorizing(schema_name, projection):
    schema = json.loads((SCHEMA_DIRECTORY / schema_name).read_text(encoding="utf-8"))
    validator = validator_for(schema)(schema)
    validator.validate(projection)

    with pytest.raises(ValidationError):
        validator.validate({**projection, "execution_authorized": True})
    with pytest.raises(ValidationError):
        validator.validate({**projection, "private_value": "must-not-be-serialized"})


